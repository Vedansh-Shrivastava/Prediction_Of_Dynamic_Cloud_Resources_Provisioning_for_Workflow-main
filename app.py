from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import streamlit as st
from keras.models import load_model

ROOT = Path(__file__).resolve().parent
ARTIFACT_DIR = ROOT / "artifacts"
DATA_PATH = ROOT / "AzureReadings_at_a_timestamp.csv"
FEATURES = ["min cpu", "max cpu", "avg cpu"]
LOOK_BACK = 5

st.set_page_config(
    page_title="Azure workload forecast",
    page_icon="📈",
    layout="wide",
)

st.markdown(
    """
    <style>
    [data-testid="stAppViewContainer"] { background: #f4f7f5; }
    [data-testid="stHeader"] { background: rgba(0,0,0,0); }
    .hero { padding: 2rem 0 1rem; }
    .hero h1 { color: #102a43; font-size: 2.7rem; margin-bottom: .35rem; }
    .hero p { color: #52606d; font-size: 1.08rem; max-width: 700px; }
    [data-testid="stMetricValue"] { color: #0f766e; }
    </style>
    """,
    unsafe_allow_html=True,
)


def artifacts_available() -> bool:
    return (ARTIFACT_DIR / "workload_lstm.keras").exists() and (
        ARTIFACT_DIR / "workload_scaler.joblib"
    ).exists()


@st.cache_resource
def load_artifacts():
    return load_model(ARTIFACT_DIR / "workload_lstm.keras"), joblib.load(
        ARTIFACT_DIR / "workload_scaler.joblib"
    )


st.markdown(
    '<div class="hero"><h1>Azure workload forecast</h1><p>Estimate the next five-minute CPU workload from the latest five readings.</p></div>',
    unsafe_allow_html=True,
)

if not artifacts_available():
    st.error("The saved model is not available yet.")
    st.code("python train_model.py\nstreamlit run app.py", language="powershell")
    st.stop()

model, scaler = load_artifacts()

with st.sidebar:
    st.subheader("Input source")
    uploaded = st.file_uploader("Upload a CSV", type=["csv"])
    st.caption("The CSV must contain min cpu, max cpu, and avg cpu columns. The last five rows are used.")

if uploaded is not None:
    source = pd.read_csv(uploaded)
    missing = [feature for feature in FEATURES if feature not in source.columns]
    if missing:
        st.error(f"Missing columns: {', '.join(missing)}")
        st.stop()
    default_values = source[FEATURES].tail(LOOK_BACK).astype(float).reset_index(drop=True)
else:
    source = pd.read_csv(DATA_PATH)
    default_values = source[FEATURES].tail(LOOK_BACK).astype(float).reset_index(drop=True)

if len(default_values) < LOOK_BACK:
    st.error(f"At least {LOOK_BACK} rows are required to make a forecast.")
    st.stop()

left, right = st.columns([1.15, 0.85], gap="large")
with left:
    st.subheader("Latest readings")
    readings = st.data_editor(
        default_values,
        use_container_width=True,
        hide_index=True,
        num_rows="fixed",
        column_config={
            "min cpu": st.column_config.NumberColumn("Min CPU", format="%.2f"),
            "max cpu": st.column_config.NumberColumn("Max CPU", format="%.2f"),
            "avg cpu": st.column_config.NumberColumn("Average CPU", format="%.2f"),
        },
    )
    predict = st.button("Predict next interval", type="primary", use_container_width=True)

with right:
    st.subheader("Forecast")
    st.caption("Predicted workload for the next 5-minute interval")
    if predict:
        try:
            values = readings[FEATURES].astype("float32").to_numpy()
            if not np.isfinite(values).all() or (values < 0).any():
                raise ValueError("Values must be finite and non-negative.")
            scaled = scaler.transform(values)
            prediction = model.predict(scaled[np.newaxis, :, :], verbose=0)
            forecast = scaler.inverse_transform(prediction)[0]
            metrics = dict(zip(FEATURES, forecast))
            st.metric("Minimum CPU", f"{metrics['min cpu']:,.0f}")
            st.metric("Maximum CPU", f"{metrics['max cpu']:,.0f}")
            st.metric("Average CPU", f"{metrics['avg cpu']:,.0f}")
        except ValueError as error:
            st.error(str(error))
    else:
        st.info("Enter or upload five recent readings, then run the forecast.")

st.divider()
st.caption("This forecast is generated by the saved LSTM model trained on the bundled Azure CPU workload dataset.")
